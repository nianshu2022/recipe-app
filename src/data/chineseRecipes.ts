/** 生成确定性 UUID（基于名称哈希，保证每次调用结果一致） */
function deterministicId(name: string): string {
  let h1 = 0, h2 = 0
  for (let i = 0; i < name.length; i++) {
    const c = name.charCodeAt(i)
    h1 = ((h1 << 5) - h1 + c) >>> 0
    h2 = ((h2 << 7) - h2 + c) >>> 0
  }
  const a = h1.toString(16).padStart(8, '0')
  const b = (h2 >>> 16).toString(16).padStart(4, '0')
  const c = (h2 & 0xffff).toString(16).padStart(4, '0')
  return `${a}-${b}-4${c.slice(1)}-8${b.slice(1)}-${a.slice(4)}${c}${b}`
}

