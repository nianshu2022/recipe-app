function toRecipe(template: (typeof recipes)[number]): Recipe {
  const { _emoji, _bg, ...rest } = template
  return {
    ...rest,
    coverImage: foodSvg(_emoji, _bg[0], _bg[1]),
    id: deterministicId(template.name),
    userId: 'local',
    syncStatus: 'pending',
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  }
}

export function getRandomChineseRecipe(): Recipe {
  return toRecipe(recipes[Math.floor(Math.random() * recipes.length)])
}

export function getRandomChineseRecipes(count: number): Recipe[] {
  const shuffled = [...recipes].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(count, shuffled.length)).map(toRecipe)
}

export function getAllRecipes(): Recipe[] {
  return recipes.map(toRecipe)
}
